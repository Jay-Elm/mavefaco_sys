function parseArgs(argv) {
  const [command, ...rest] = argv;
  const opts = { command, yes: rest.includes("--yes"), env: null };
  const i = rest.indexOf("--env");
  if (i >= 0) opts.env = rest[i + 1];
  return opts;
}

function readEnvFile(path) {
  const out = {};
  for (const line of fs.readFileSync(path, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    let v = m[2];
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    out[m[1]] = v;
  }
  return out;
}

const maskEmail = (e) => {
  const [u, d] = e.split("@");
  return `${u.slice(0, 2)}${"*".repeat(Math.max(1, u.length - 2))}@${d}`;
};

// ---------- dates (Philippine time, like the app) ----------

const PH = 8 * 3600 * 1000;
const todayPH = (now = new Date()) => new Date(now.getTime() + PH).toISOString().slice(0, 10);
const addDays = (d, n) => {
  const t = new Date(`${d}T00:00:00Z`);
  t.setUTCDate(t.getUTCDate() + n);
  return t.toISOString().slice(0, 10);
};
const atPH = (d, hour = 9) => new Date(`${d}T${String(hour).padStart(2, "0")}:00:00+08:00`);

