const PRODUCT_BUCKET = "product-images";
const ID_BUCKET = "id-verification";
const PRIVATE_BUCKET = "private-images";

function publicPath(url) {
  if (!url) return null;
  const marker = `/storage/v1/object/public/${PRODUCT_BUCKET}/`;
  const i = url.indexOf(marker);
  return i >= 0 ? decodeURIComponent(url.slice(i + marker.length)) : null;
}

async function deleteFromStorage(env, bucket, paths) {
  const list = [...new Set(paths.filter(Boolean))];
  if (list.length === 0) return { bucket, deleted: 0, ok: true };
  if (!env.SUPABASE_URL || !env.SUPABASE_SERVICE_ROLE_KEY) return { bucket, deleted: 0, ok: false, reason: "no SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY" };
  let deleted = 0;
  for (let i = 0; i < list.length; i += 100) {
    const res = await fetch(`${env.SUPABASE_URL}/storage/v1/object/${bucket}`, {
      method: "DELETE",
      headers: { Authorization: `Bearer ${env.SUPABASE_SERVICE_ROLE_KEY}`, apikey: env.SUPABASE_SERVICE_ROLE_KEY, "Content-Type": "application/json" },
      body: JSON.stringify({ prefixes: list.slice(i, i + 100) }),
    });
    if (!res.ok) return { bucket, deleted, ok: false, reason: `storage answered ${res.status}` };
    deleted += (await res.json()).length;
  }
  return { bucket, deleted, ok: true };
}

/** Image files that belong to the given users (and their products and messages). */
async function imagesOf(db, userIds) {
  const q = async (sql) => (await db.query(sql, [userIds])).rows;
  const products = await q(`SELECT "imageUrl" AS p FROM "Product" WHERE "farmerId" = ANY($1)`);
  const qrs = await q(`SELECT "gcashQrUrl" AS p, "gcashQrPath" AS priv FROM "User" WHERE id = ANY($1)`);
  const chat = await q(`SELECT "imagePath" AS p FROM "Message" WHERE "imagePath" IS NOT NULL AND ("senderId" = ANY($1) OR "receiverId" = ANY($1))`);
  const ids = await q(`SELECT "frontPath", "backPath", "selfiePath" FROM "IdSubmission" WHERE "userId" = ANY($1)`);
  return {
    [PRODUCT_BUCKET]: [...products.map((r) => publicPath(r.p)), ...qrs.map((r) => publicPath(r.p))],
    [PRIVATE_BUCKET]: [...qrs.map((r) => r.priv), ...chat.map((r) => r.p)],
    [ID_BUCKET]: ids.flatMap((r) => [r.frontPath, r.backPath, r.selfiePath]),
  };
}

