/**
 * Deletes every row that belongs to `userIds`, in an order the foreign keys
 * allow. With `everything`, also clears the tables reset empties whole.
 */
async function deleteUsersData(db, userIds, { everything = false } = {}) {
  const run = async (sql, params = [userIds]) => (await db.query(sql, params)).rowCount;
  const n = {};
  const theirProducts = `SELECT id FROM "Product" WHERE "farmerId" = ANY($1)`;
  const theirOrders = `SELECT id FROM "Order" WHERE "customerId" = ANY($1) OR id IN (SELECT "orderId" FROM "OrderItem" WHERE "productId" IN (${theirProducts}))`;

  n.Notice = await run(`DELETE FROM "Notice" WHERE "recipientId" = ANY($1) OR "productId" IN (${theirProducts})`);
  n.ConversationHide = await run(`DELETE FROM "ConversationHide" WHERE "userId" = ANY($1) OR "otherId" = ANY($1)`);
  n.Message = await run(`DELETE FROM "Message" WHERE "senderId" = ANY($1) OR "receiverId" = ANY($1) OR "orderId" IN (${theirOrders})`);
  n.Review = await run(`DELETE FROM "Review" WHERE "customerId" = ANY($1) OR "productId" IN (${theirProducts})`);
  const orderIds = (await db.query(theirOrders, [userIds])).rows.map((r) => r.id);
  n.OrderItem = await run(`DELETE FROM "OrderItem" WHERE "orderId" = ANY($1)`, [orderIds]);
  n.Order = await run(`DELETE FROM "Order" WHERE id = ANY($1)`, [orderIds]);
  n.CropLog = await run(`DELETE FROM "CropLog" WHERE "plantingId" IN (SELECT id FROM "Planting" WHERE "farmerId" = ANY($1))`);
  n.Planting = await run(`DELETE FROM "Planting" WHERE "farmerId" = ANY($1) OR "productId" IN (${theirProducts})`);
  n.Product = await run(`DELETE FROM "Product" WHERE "farmerId" = ANY($1)`);
  n.IdSubmission = await run(`DELETE FROM "IdSubmission" WHERE "userId" = ANY($1)`);
  n.AiReport = everything ? await run(`DELETE FROM "AiReport"`, []) : await run(`DELETE FROM "AiReport" WHERE "createdById" = ANY($1)`);
  n.AuditLog = everything ? await run(`DELETE FROM "AuditLog"`, []) : await run(`DELETE FROM "AuditLog" WHERE "userId" = ANY($1)`);
  if (everything) {
    n.Announcement = await run(`DELETE FROM "Announcement"`, []);
    n.RateLimit = await run(`DELETE FROM "RateLimit"`, []);
  } else {
    n.Announcement = await run(`DELETE FROM "Announcement" WHERE "authorId" = ANY($1) OR title = ANY($2)`, [userIds, DEMO_ANNOUNCEMENTS.map((a) => a.title)]);
  }
  for (const t of ["EmailVerificationToken", "PasswordResetToken", "EmailChangeToken", "TotpBackupCode"])
    n[t] = await run(`DELETE FROM "${t}" WHERE "userId" = ANY($1)`);
  n.User = await run(`DELETE FROM "User" WHERE id = ANY($1)`);
  return n;
}

async function withTransaction(db, fn) {
  await db.query("BEGIN");
  try {
    const out = await fn();
    await db.query("COMMIT");
    return out;
  } catch (e) {
    await db.query("ROLLBACK");
    throw e;
  }
}

export async function reset(db, env, { yes }) {
  const admins = (await db.query(`SELECT id FROM "User" WHERE role = 'admin' AND "deletedAt" IS NULL`)).rows.map((r) => r.id);
  if (admins.length === 0) throw new Error("No admin account found; refusing to delete everything.");
  const others = (await db.query(`SELECT id FROM "User" WHERE NOT (id = ANY($1))`, [admins])).rows.map((r) => r.id);
  const images = await imagesOf(db, others);
  if (!yes) {
    console.log(`Would keep ${admins.length} admin account(s) and delete ${others.length} other account(s) with everything they made,`);
    console.log("all announcements, the audit log, AI reports and rate-limit counters, and these images:");
    for (const [b, p] of Object.entries(images)) console.log(`  ${b}: ${p.filter(Boolean).length}`);
    console.log("Run again with --yes to do it.");
    return null;
  }
  const n = await withTransaction(db, () => deleteUsersData(db, others, { everything: true }));
  const storage = [];
  for (const [b, p] of Object.entries(images)) storage.push(await deleteFromStorage(env, b, p));
  return { kept: admins.length, deleted: n, storage };
}

/** Every row of every table, written to `file` as JSON (a copy to restore from by hand). */
export async function backup(db, file) {
  const tables = (await db.query(`SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename <> '_prisma_migrations' ORDER BY tablename`)).rows;
  const out = { takenAt: new Date().toISOString(), tables: {} };
  for (const { tablename } of tables) out.tables[tablename] = (await db.query(`SELECT * FROM "${tablename}"`)).rows;
  fs.mkdirSync(file.replace(/[\\/][^\\/]*$/, ""), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(out));
  return Object.values(out.tables).reduce((s, rows) => s + rows.length, 0);
}

